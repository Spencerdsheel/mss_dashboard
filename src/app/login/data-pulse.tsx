function PulseRing({ delay, cx, cy }: { delay: number; cx: number; cy: number }) {
  return (
    <circle
      cx={cx}
      cy={cy}
      r={1}
      fill="none"
      stroke="#ff682c"
      strokeWidth={0.4}
      style={{ animation: `pulse 2s ${delay}s ease-out infinite` }}
    />
  );
}

function ConnectionLine({
  x1,
  y1,
  x2,
  y2,
  delay,
}: {
  x1: number;
  y1: number;
  x2: number;
  y2: number;
  delay: number;
}) {
  return (
    <line
      x1={x1}
      y1={y1}
      x2={x2}
      y2={y2}
      stroke="#ff682c"
      strokeWidth={0.3}
      style={{ animation: `fadeInOut 4s ${delay}s ease-in-out infinite` }}
    />
  );
}

export function DataPulseMap() {
  const [activeCity, setActiveCity] = useState<number | null>(null);

  useEffect(() => {
    const interval = setInterval(() => {
      setActiveCity(Math.floor(Math.random() * CITIES.length));
      setTimeout(() => setActiveCity(null), 2000);
    }, 3000);
    return () => clearInterval(interval);
  }, []);

  return (
    <div className="absolute inset-0 flex items-center justify-center overflow-hidden bg-[#020617]">
      <svg viewBox="0 5 100 76" className="h-full w-full" preserveAspectRatio="xMidYMid meet">
        <style>{`
          @keyframes pulse {
            0% { r: 1; opacity: 0.7; }
            100% { r: 4; opacity: 0; }
          }
          @keyframes fadeInOut {
            0%, 100% { opacity: 0; }
            25%, 75% { opacity: 0.4; }
          }
          @keyframes dotPulse {
            0%, 100% { transform: scale(1); }
            50% { transform: scale(1.3); }
          }
          @keyframes labelFade {
            from { opacity: 0; }
            to { opacity: 1; }
          }
        `}</style>

        {/* World map — dot matrix */}
        {LAND_DOTS.map(([x, y], i) => (
          <circle key={i} cx={x} cy={y} r={0.45} fill="rgba(255,255,255,0.18)" />
        ))}

        {/* Connection lines between cities */}
        {CONNECTIONS.map(([a, b], i) => (
          <ConnectionLine
            key={`conn-${i}`}
            x1={CITIES[a].x}
            y1={CITIES[a].y}
            x2={CITIES[b].x}
            y2={CITIES[b].y}
            delay={i * 0.5}
          />
        ))}

        {/* City pins */}
        {CITIES.map((city, i) => (
          <g key={city.name}>
            {/* Pulse rings */}
            <PulseRing cx={city.x} cy={city.y} delay={i * 0.3} />
            {/* Core dot */}
            <circle
              cx={city.x}
              cy={city.y}
              r={0.8}
              fill="#ff682c"
              style={{
                animation: `dotPulse 2s ${i * 0.3}s infinite`,
                transformOrigin: `${city.x}px ${city.y}px`,
              }}
            />
            {/* Glow */}
            <circle cx={city.x} cy={city.y} r={2} fill="#ff682c" opacity={0.08} />
          </g>
        ))}

        {/* Active city label */}
        {activeCity !== null && (
          <g style={{ animation: "labelFade 0.3s ease-in" }}>
            <rect
              x={CITIES[activeCity].x - 8}
              y={CITIES[activeCity].y - 8}
              width={16}
              height={6}
              rx={1}
              fill="rgba(15,23,42,0.9)"
              stroke="rgba(255,104,44,0.3)"
              strokeWidth={0.3}
            />
            <text
              x={CITIES[activeCity].x}
              y={CITIES[activeCity].y - 4.5}
              textAnchor="middle"
              fill="#ff7a45"
              fontSize={2.2}
              fontWeight={600}
            >
              {CITIES[activeCity].name}
            </text>
          </g>
        )}
      </svg>

      {/* Static caption */}
      <div className="absolute bottom-20 left-8 text-xs text-white/40">
        Global coverage · 50+ cities
      </div>
    </div>
  );
}
